// Assembles README.md: the drawing set, sheet by sheet. Sections push blocks into ctx.md.
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
// markdown text: keep characters that would start formatting from doing so
const md = s => esc(s).replace(/([*_`[\]\\|])/g, '\\$1');

export const img = (src, alt, o = {}) =>
  `<img src="assets/${src}" alt="${esc(alt)}" width="${o.width || '100%'}"${o.height ? ` height="${o.height}"` : ''}>`;
export const link = (href, inner) => `<a href="${esc(href)}">${inner}</a>`;

// The whole drawing set as plain text: for phones, screen readers and anyone who wants to skim.
function asText(p, ctx) {
  const featured = ctx.featured || [];
  const item = q => `- [${md(q.name)}](${q.url}) · ${md(q.kind)}. ${md(q.line)} <sub>${md(q.stack.join(', '))}</sub>`;
  const tb = Object.entries(p.toolbox).map(([k, v]) => `${k[0].toUpperCase() + k.slice(1)}: ${md(v.join(', '))}`).join(' · ');
  return [
    '<details>',
    '<summary><b>Read the drawing set as text</b> · projects, toolbox, contact</summary>',
    '',
    `**${md(p.name)}**, ${md(p.identity.join(' · '))}. ${md(p.role)} at ${md(p.company)} (previously ${md(p.previousRole)}), ${md(p.location)}. ${md(p.education)}.`,
    '',
    '**Principal assemblies**',
    '',
    ...p.projects.filter(q => featured.includes(q.key)).map(item),
    '',
    '**Details**',
    '',
    ...p.projects.filter(q => !featured.includes(q.key)).map(item),
    '',
    `**Bill of materials** · ${tb}`,
    '',
    `**Distribution** · ${(ctx.dests || []).map(d => `[${md(d.value)}](${d.href})`).join(' · ')}`,
    '',
    '</details>',
  ].join('\n');
}

export function readme(profile, data, ctx) {
  const p = profile, L = p.links;
  const head = `<!-- THE BLUEPRINT · generated by build.mjs from profile.json + data.json (${data.generatedAt.slice(0, 10)}). Do not edit by hand. -->`;
  const hero = `<p align="center">${link(L.website, img('hero.svg', `${p.name}: ${p.identity[0]}. ${p.role} at ${p.company}, ${p.location}.`))}</p>`;
  // a real-text caption under the cover sheet: readable on any screen, by any reader
  const founder = p.identity.find(s => /found/i.test(s));
  const caption = `<p align="center"><b>${esc(p.name)}</b> · ${esc(p.identity[0])} · ${esc(p.role)} @ ${esc(p.company)} · ${esc(p.location)}<br>` +
    `<sub>${esc(p.education)}${founder ? ` · ${esc(founder.split(',')[0])}` : ''}</sub></p>`;
  const links = [L.website && link(L.website, 'Website'), L.linkedin && link(L.linkedin, 'LinkedIn'), L.cv && link(L.cv, 'CV (PDF)'), L.github && link(L.github, 'GitHub')].filter(Boolean);
  const transmittal = `<p align="center"><sub>${links.join(' · ')} · drawing set regenerated daily from live GitHub data, last ${data.generatedAt.slice(0, 10)}</sub></p>`;
  const body = [...(ctx.md || [])];
  body.splice(ctx.textAt ?? body.length, 0, '', asText(p, ctx), '');
  return [head, '', hero, caption, '', ...body, '', transmittal, ''].join('\n');
}
